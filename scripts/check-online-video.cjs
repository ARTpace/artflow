const assert = require('node:assert/strict');
require('./register-typescript.cjs');
const { parseVideoUrl, findVideoLink, ONLINE_VIDEO_NODE } = require('../builtin-plugins/online-video/links.ts');
const bv = 'BV1B7411m7LV';
let link = parseVideoUrl(`https://www.bilibili.com/video/${bv}/?p=2`);
assert.equal(new URL(link.playerUrl).searchParams.get('bvid'), bv);
assert.equal(new URL(link.playerUrl).searchParams.get('p'), '2');
assert.equal(new URL(link.playerUrl).searchParams.get('autoplay'), '0');
assert.equal(new URL(parseVideoUrl('https://m.bilibili.com/video/av123').playerUrl).searchParams.get('aid'), '123');
for (const url of ['https://youtu.be/dQw4w9WgXcQ', 'https://www.youtube.com/watch?v=dQw4w9WgXcQ', 'https://youtube.com/shorts/dQw4w9WgXcQ']) assert.equal(parseVideoUrl(url).provider, 'youtube');
assert.equal(parseVideoUrl('https://cdn.example.com/a.mp4?signature=x').provider, 'direct');
assert.equal(parseVideoUrl('https://b23.tv/abc123').provider, 'bilibili-short');
assert.equal(findVideoLink(`分享一个视频 https://www.bilibili.com/video/${bv}。`).provider, 'bilibili');
for (const text of ['普通笔记', 'https://example.com/', 'javascript:alert(1)', 'https://bilibili.com.evil.test/video/' + bv, 'https://user:pass@b23.tv/abc', 'http://b23.tv/abc', 'https://b23.tv:444/abc', 'https://youtube.com/watch?v=bad', 'https://a.test/a.mp4 https://b.test/b.webm']) assert.equal(findVideoLink(text), null, text);
const React = require('react');
const { renderToStaticMarkup } = require('react-dom/server');
const { OnlineVideoCard } = require('../builtin-plugins/online-video/OnlineVideoCard.tsx');
const element = Object.freeze({ type: 'plugin-node', nodeType: ONLINE_VIDEO_NODE, data: Object.freeze({ sourceUrl: `https://www.bilibili.com/video/${bv}`, playerUrl: 'https://evil.test' }) });
const markup = renderToStaticMarkup(React.createElement(OnlineVideoCard, { element }));
assert.ok(markup.includes('加载播放器'));
assert.ok(!markup.includes('<iframe'));
assert.ok(!markup.includes('evil.test'));
const { createKernel } = require('../plugin-runtime/kernel.ts');
const { loadBuiltinPlugin } = require('../plugin-runtime/loader.ts');
const { materializeRendererContributions, getMaterializedCardComponent } = require('../plugin-runtime/renderer-materialization.ts');
const { onlineVideoPlugin } = require('../builtin-plugins/online-video/index.tsx');
const kernel = createKernel();
const { parseClipboardText } = require('../plugin-runtime/clipboard-handlers.ts');
assert.equal(parseClipboardText(`https://www.bilibili.com/video/${bv}`, { x: 0, y: 0 }), null);
const loaded = loadBuiltinPlugin(kernel, onlineVideoPlugin);
const nodes = parseClipboardText(`https://www.bilibili.com/video/${bv}`, { x: 100, y: 200 });
assert.equal(nodes[0].nodeType, ONLINE_VIDEO_NODE);
assert.equal(nodes[0].x, -140);
assert.deepEqual(JSON.parse(JSON.stringify(nodes)), nodes);
assert.equal(parseClipboardText('普通文字', { x: 0, y: 0 }), null);
materializeRendererContributions(kernel);
assert.ok(getMaterializedCardComponent(ONLINE_VIDEO_NODE));
loaded.dispose();
assert.equal(parseClipboardText(`https://www.bilibili.com/video/${bv}`, { x: 0, y: 0 }), null);
materializeRendererContributions(kernel);
assert.equal(getMaterializedCardComponent(ONLINE_VIDEO_NODE), undefined);
assert.equal(element.data.sourceUrl, `https://www.bilibili.com/video/${bv}`);
console.log('online-video: URL recognition, lazy playback, untrusted data and plugin disposal passed');
